def shared(p):
    # the shell reads this
    keys = ("theme", "name", "tagline", "wallpaper", "background", "bar", "frame", "frame_focus",
            "border", "text", "dim", "accent", "accent2", "on_accent", "urgent", "ansi",
            "radius", "border_width", "gaps", "outer_gaps", "bar_height", "opacity", "speed", "bounce", "layout")
    data = json.dumps({k: p[k] for k in keys}, indent=2) + "\n"
    write(CACHE / "kon/palette.json", data)
    write(CACHE / "aroclip/theme.json", data)


def wallpaper(p):
    if p["wallpaper"] and Path(p["wallpaper"]).is_file():
        sh("kon-wm", "wallpaper", p["wallpaper"])


GTK_SETTINGS = (CONF / "gtk-3.0/settings.ini", CONF / "gtk-4.0/settings.ini")


def cursor_installed(name):
    dirs = (HOME / ".local/share/icons", HOME / ".icons", Path("/usr/share/icons"))
    return any((d / name / "cursors").is_dir() for d in dirs)


def set_cursor(aro_value, gtk, gs):
    path = CONF / "aro/config"
    s = path.read_text() if path.exists() else ""
    if re.search(r"^\s*cursor_theme\s*=", s, re.M):
        s = re.sub(r"^(\s*cursor_theme\s*=\s*).*$", lambda m: m.group(1) + aro_value, s, count=1, flags=re.M)
        write(path, s)
    for f, name in gtk.items():
        f = Path(f)
        if f.exists() and name:
            write(f, re.sub(r"^gtk-cursor-theme-name=.*$", "gtk-cursor-theme-name=" + name,
                            f.read_text(), flags=re.M))
    if gs:
        sh("gsettings", "set", "org.gnome.desktop.interface", "cursor-theme", gs)


def cursor(p):
    name = p["cursor"]
    if name and cursor_installed(name):
        quoted = f"'{name}'" if " " in name else name
        set_cursor(quoted, {str(f): name for f in GTK_SETTINGS}, name)



def apply():
    p = load("aero")
    cursor(p)
    shared(p)
    aro(p)
    hypr(p)
    niri(p)
    sh("kon-wm", "reload")
    foot(p)
    templated(p)
    sh("makoctl", "reload")
    gtk(p)
    btop(p)
    cava(p)
    starship(p)
    fastfetch(p)
    qutebrowser(p)
    wallpaper(p)
    sh("qs", "-c", "aroclip", "ipc", "call", "kon", "changed", "aero", p["name"], p["tagline"])
    print(f"{p['name']}: {p['tagline']}")


def main():
    arg = sys.argv[1] if len(sys.argv) > 1 else "aero"
    if arg in ("aero", "apply"):
        apply()
    elif arg == "restore":
        wallpaper(load("aero"))
    else:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    return 0

if __name__ == "__main__":
    sys.exit(main())
