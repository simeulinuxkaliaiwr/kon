#!/usr/bin/env python3
"""kon - the aero theme for aro, Hyprland and niri: colours, shape and motion in every app.

    kon                 apply it (also: kon aero)
    kon restore         put back the theme's wallpaper (for aro's exec)

The theme is ~/.config/kon/themes/aero.json and the app templates are in
templates/; edit either and run kon again.
"""

import json
import os
import re
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
CONF = HOME / ".config"
KON = CONF / "kon"
THEMES = KON / "themes"
CACHE = HOME / ".cache"
os.environ["PATH"] = f"{HOME}/.local/bin:{os.environ.get('PATH', '')}"

SHAPE = {"radius": 5, "border_width": 2, "gaps": 9, "outer_gaps": 9, "bar_height": 30, "opacity": 0.92,
         "header_gloss": 0.0, "header_opacity": 1.0}
MOTION = {"speed": 1.0, "bounce": 1.0}


def sh(*cmd):
    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".kon-tmp")
    tmp.write_text(text)
    tmp.replace(path)


def rgb(h):
    return ", ".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def flatten(tid, t):
    # everything the templates need
    p = dict(t["colors"])
    p.update(dict(SHAPE, **t.get("shape", {})))
    p.update(dict(MOTION, **t.get("motion", {})))
    p["theme"] = tid
    p["cache"] = str(CACHE)
    p["name"] = t.get("name", tid)
    p["tagline"] = t.get("tagline", "")
    p["layout"] = "aero"
    p["cursor"] = t.get("cursor", "")   # empty keeps the user's cursor
    wp = t.get("wallpaper")
    p["wallpaper"] = str(Path(os.path.expanduser(wp)).resolve()) if wp else ""
    p["gaps_half"] = max(0, round(p["gaps"] / 2))   # Hyprland's gaps_in is per side
    p["frame_rgb"] = rgb(p["frame"])
    p["accent_rgb"] = rgb(p["accent"])
    return p


def load(tid):
    return flatten(tid, json.loads((THEMES / f"{tid}.json").read_text()))


def render(template, p):
    return re.sub(r"\{\{(\w+)\}\}", lambda m: str(p[m.group(1)]), template)


# apps

def templated(p, names=("mako", "swaylock", "fuzzel.ini")):
    targets = {
        "mako": CONF / "mako/config",
        "swaylock": CONF / "swaylock/config",
        "fuzzel.ini": CONF / "fuzzel/fuzzel.ini",
    }
    for name in names:
        write(targets[name], render((KON / "templates" / name).read_text(), p))


ARO_COLOURS = {
    "background": lambda p: p["background"] + "ff",
    "frame": lambda p: p["frame"] + "ff",
    "frame_focus": lambda p: p["frame_focus"] + "ff",
    "border_color": lambda p: p["border"] + "ff",
    "accent": lambda p: p["accent"] + "ff",
    "accent_soft": lambda p: p["accent"] + "4d",
    "text": lambda p: p["text"] + "ff",
    "text_dim": lambda p: p["dim"] + "ff",
    "bar_color": lambda p: p["bar"] + "ff",
    "urgent": lambda p: p["urgent"] + "ff",
    "drop_fill": lambda p: p["accent"] + "1f",
    "drop_line": lambda p: p["accent"] + "cc",
}

# aro's animation times at speed 1
ARO_MOTION = {"anim_ms": 340, "fullscreen_anim_ms": 220, "focus_anim_ms": 160,
              "drop_anim_ms": 160, "workspace_slide_ms": 220}


def aro(p):
    path = CONF / "aro/config"
    if not path.exists():
        return
    s = path.read_text()
    for key, val in ARO_COLOURS.items():
        s = re.sub(rf"^(\s*{key}\s*=\s*)(0x|#)?[0-9a-fA-F]{{6,8}}", lambda m: m.group(1) + "0x" + val(p),
                   s, flags=re.M)
    nums = {"radius": p["radius"], "border": p["border_width"], "gaps": p["gaps"], "outer_gaps": p["outer_gaps"]}
    nums.update({k: max(1, round(v / max(0.1, p["speed"]))) for k, v in ARO_MOTION.items()})
    for key, val in nums.items():
        s = re.sub(rf"^(\s*{key}\s*=\s*)\d+(\.\d+)?", lambda m: m.group(1) + str(int(val)), s, flags=re.M)
    # only touch these if they're already there
    for key in ("header_gloss", "header_opacity"):
        s = re.sub(rf"^(\s*{key}\s*=\s*)\d+(\.\d+)?", lambda m: m.group(1) + f"{float(p[key]):g}", s, flags=re.M)
    if "exec = kon restore" not in s:
        s = s.replace("# ── keyboard", "# kon: the current theme's wallpaper, see ~/.config/kon\nexec = kon restore\n\n# ── keyboard", 1)
    write(path, s)


def hypr(p):
    # kon-aero.lua does require("kon")
    if (CONF / "hypr/kon-aero.lua").exists():
        write(CONF / "hypr/kon.lua", render((KON / "templates/hypr-kon.lua").read_text(), p))


def niri(p):
    # config.kdl does include "kon.kdl"
    if (CONF / "niri/config.kdl").exists():
        write(CONF / "niri/kon.kdl", render((KON / "templates/niri-kon.kdl").read_text(), p))


def foot(p):
    a = p["ansi"]
    alpha = min(1.0, max(0.3, round(p["opacity"] - 0.07, 2)))
    out = ["# generated by kon", "", "[colors-dark]",
           f"foreground={p['text']}", f"background={p['background']}", f"alpha={alpha}", "blur=yes"]
    out += [f"regular{i}={a[i]}" for i in range(8)] + [f"bright{i}={a[i + 8]}" for i in range(8)]
    out += [f"selection-foreground={p['on_accent']}", f"selection-background={p['accent']}",
            f"cursor={p['background']} {p['accent']}", f"urls={p['accent']}",
            f"jump-labels={p['on_accent']} {p['accent']}", ""]
    write(CONF / "foot/themes/kon", "\n".join(out))
    path = CONF / "foot/foot.ini"
    s = path.read_text()
    s = re.sub(r"^include=.*themes/\w+$", "include=~/.config/foot/themes/kon", s, flags=re.M)
    s = re.sub(r"^\[colors-dark\]\n(?:(?!\[).*\n?)*", "", s, flags=re.M)
    s = re.sub(r"^initial-color-theme=.*\n", "", s, flags=re.M)
    write(path, s)
    terminals(p)


def terminals(p):
    # recolour open terminals, like pywal
    a = p["ansi"]
    seq = "".join(f"\033]4;{i};#{a[i]}\033\\" for i in range(16))
    seq += (f"\033]10;#{p['text']}\033\\\033]11;#{p['background']}\033\\\033]12;#{p['accent']}\033\\"
            f"\033]17;#{p['accent']}\033\\\033]19;#{p['on_accent']}\033\\")
    data = seq.encode()
    uid = os.getuid()
    for pts in Path("/dev/pts").glob("[0-9]*"):
        try:
            if pts.stat().st_uid != uid:
                continue
            fd = os.open(pts, os.O_WRONLY | os.O_NOCTTY | os.O_NONBLOCK)
            try:
                os.write(fd, data)
            finally:
                os.close(fd)
        except OSError:
            pass


