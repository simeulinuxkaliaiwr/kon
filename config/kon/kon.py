def starship(p):
    a = p["ansi"]
    cols = {
        "blue": a[4], "red": a[1], "green": a[2], "yellow": a[3], "cyan": a[6], "magenta": a[5],
        "white": p["text"], "black": a[0], "rosewater": p["accent2"], "flamingo": a[9], "pink": a[13],
        "mauve": a[5], "maroon": a[1], "peach": p["accent2"], "teal": a[6], "sky": a[14],
        "sapphire": a[12], "lavender": a[13], "text": p["text"], "subtext1": p["text"],
        "subtext0": p["dim"], "overlay2": p["dim"], "overlay1": p["dim"], "overlay0": p["border"],
        "surface2": p["border"], "surface1": p["frame_focus"], "surface0": p["frame"],
        "base": p["background"], "mantle": p["bar"], "crust": p["bar"],
        "accent": p["accent"],
    }
    block = "# >>> kon\n[palettes.kon]\n" + "".join(f'{k} = "#{v}"\n' for k, v in cols.items()) + "# <<< kon\n"
    path = CONF / "starship.toml"
    if not path.exists():
        return
    s = path.read_text()
    s = re.sub(r'^palette = ".*"$', 'palette = "kon"', s, count=1, flags=re.M)
    if "# >>> kon" in s:
        s = re.sub(r"# >>> kon.*?# <<< kon\n", lambda m: block, s, flags=re.S)
    else:
        s = s.rstrip("\n") + "\n\n" + block
    write(path, s)


def fastfetch(p):
    path = CONF / "fastfetch/config.jsonc"
    try:
        cfg = json.loads(path.read_text())
    except (OSError, ValueError):
        return
    cfg.setdefault("display", {})["color"] = {"keys": "#" + p["accent"], "title": "#" + p["accent2"]}
    cfg["display"].setdefault("percent", {})["color"] = {"green": "#" + p["ansi"][2],
                                                           "yellow": "#" + p["ansi"][3],
                                                           "red": "#" + p["urgent"]}
    write(path, json.dumps(cfg, indent=2) + "\n")


